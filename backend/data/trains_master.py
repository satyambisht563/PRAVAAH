def min_to_hhmm(m: Optional[int]) -> Optional[str]:
    if m is None:
        return None
    norm = ((int(m) % 1440) + 1440) % 1440
    hh = norm // 60
    mm = norm % 60
    return f"{hh:02d}:{mm:02d}"

