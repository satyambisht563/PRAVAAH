def get_train_by_number(train_no: str) -> Optional[Dict[str, Any]]:
    for t in TRAINS:
        if t["number"] == str(train_no) or t["id"] == str(train_no):
            return t
    return None

def is_train_scheduled_on_day(train_no: str, day_abbr: str) -> bool:
    t = get_train_by_number(train_no)
    if not t:
        return False
    return day_abbr.upper() in [d.upper() for d in t.get("running_days", [])]
